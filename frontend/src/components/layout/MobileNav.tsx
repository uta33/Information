import { NavLink } from "react-router-dom";
import { useSummary, useNotifications } from "../../hooks/useNotifications";

const tabs = [
  { to: "/", label: "ホーム", icon: HomeIcon },
  { to: "/inbox", label: "受信", icon: InboxIcon },
  { to: "/saved", label: "保存", icon: BookmarkIcon },
  { to: "/settings", label: "設定", icon: SettingsIcon },
];

export default function MobileNav() {
  const { data: summary } = useSummary();
  const { unreadCount } = useNotifications();
  const unread = unreadCount;

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 bg-slate-900 border-t border-slate-800 safe-bottom">
      <div className="flex">
        {tabs.map(({ to, label, icon: Icon }) => (
          <NavLink
            key={to}
            to={to}
            end={to === "/"}
            className={({ isActive }) =>
              `flex-1 flex flex-col items-center gap-0.5 py-3 text-xs transition-colors ${
                isActive ? "text-indigo-400" : "text-slate-500"
              }`
            }
          >
            <div className="relative">
              <Icon className="w-6 h-6" />
              {to === "/inbox" && unread > 0 && (
                <span className="absolute -top-1 -right-1 min-w-[16px] h-4 bg-red-500 text-white text-[10px] font-bold rounded-full flex items-center justify-center px-0.5">
                  {unread > 99 ? "99+" : unread}
                </span>
              )}
            </div>
            <span>{label}</span>
          </NavLink>
        ))}
      </div>
    </nav>
  );
}

